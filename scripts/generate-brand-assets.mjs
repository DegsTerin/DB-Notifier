/**
 * Generates the provider-neutral DB-Notifier database mark for Web and Windows surfaces.
 * The implementation uses only Node.js primitives so CI can verify the SVG and ICO outputs cross-platform.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const background = [11, 92, 173, 255];
const foreground = [255, 255, 255, 255];
const accent = [88, 201, 54, 255];
const outputs = {
  designSystemSvg: join(root, "design-system/assets/dbnotifier-database.svg"),
  dashboardSvg: join(root, "src/DBNotifier.Dashboard.Web/public/dbnotifier-icon.svg"),
  windowsIcon: join(root, "src/DBNotifier.Desktop.Wpf/Assets/DBNotifier.ico"),
};

/** Builds the accessible vector master used by browser surfaces and Design System documentation. */
function buildSvg() {
  return `<!-- Generated by scripts/generate-brand-assets.mjs; do not edit directly. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect x="2" y="2" width="60" height="60" rx="14" fill="#0B5CAD"/>
  <g fill="none" stroke="#FFFFFF" stroke-width="3" stroke-linecap="round" stroke-linejoin="round">
    <ellipse cx="27" cy="17" rx="15" ry="5.5"/>
    <path d="M12 17v11c0 3.04 6.72 5.5 15 5.5S42 31.04 42 28V17"/>
    <path d="M12 28v11c0 3.04 6.72 5.5 15 5.5 2.34 0 4.56-.2 6.54-.57"/>
  </g>
  <path d="M39 45.5v-5.25a7 7 0 0 1 14 0v5.25l3 4.5H36Z" fill="#58C936" stroke="#FFFFFF" stroke-width="2.5" stroke-linejoin="round"/>
  <path d="M43 52a3 3 0 0 0 6 0" fill="none" stroke="#FFFFFF" stroke-width="2.5" stroke-linecap="round"/>
</svg>
`;
}

/** Returns whether a point lies inside the rounded-square brand background. */
function insideRoundedSquare(x, y) {
  const nearestX = Math.max(16, Math.min(48, x));
  const nearestY = Math.max(16, Math.min(48, y));
  return x >= 2 && x <= 62 && y >= 2 && y <= 62 && Math.hypot(x - nearestX, y - nearestY) <= 14;
}

/** Calculates the shortest distance from a point to a finite line segment. */
function distanceToSegment(x, y, x1, y1, x2, y2) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const denominator = dx * dx + dy * dy;
  const projection = denominator === 0 ? 0 : Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / denominator));
  return Math.hypot(x - (x1 + projection * dx), y - (y1 + projection * dy));
}

/** Returns whether a point overlaps the balanced outline used by the database-cylinder mark. */
function insideDatabaseStroke(x, y) {
  const strokeRadius = 1.5;
  let previousX = 42;
  let previousY = 17;
  for (let step = 1; step <= 64; step += 1) {
    const angle = (Math.PI * 2 * step) / 64;
    const currentX = 27 + 15 * Math.cos(angle);
    const currentY = 17 + 5.5 * Math.sin(angle);
    if (distanceToSegment(x, y, previousX, previousY, currentX, currentY) <= strokeRadius) return true;
    previousX = currentX;
    previousY = currentY;
  }
  if (distanceToSegment(x, y, 12, 17, 12, 39) <= strokeRadius ||
      distanceToSegment(x, y, 42, 17, 42, 28) <= strokeRadius) return true;
  for (const centreY of [28, 39]) {
    previousX = 12;
    let previousY = centreY;
    for (let step = 1; step <= 32; step += 1) {
      const angle = Math.PI - (Math.PI * step) / 32;
      const currentX = 27 + 15 * Math.cos(angle);
      const currentY = centreY + 5.5 * Math.sin(angle);
      if (distanceToSegment(x, y, previousX, previousY, currentX, currentY) <= strokeRadius) return true;
      previousX = currentX;
      previousY = currentY;
    }
  }
  return false;
}

/** Returns whether a point lies within the lower-right notification bell accent. */
function insideBellFill(x, y) {
  if (y >= 45.5 && y <= 50 && x >= 36 + (50 - y) * (3 / 4.5) && x <= 56 - (50 - y) * (3 / 4.5)) return true;
  const bodyHalfWidth = 7 * Math.sqrt(Math.max(0, 1 - ((y - 40.25) / 7) ** 2));
  return y >= 33.25 && y <= 45.5 && Math.abs(x - 46) <= bodyHalfWidth;
}

/** Returns whether a point overlaps the white bell outline or clapper. */
function insideBellStroke(x, y) {
  const strokeRadius = 1.25;
  const segments = [[36, 50, 39, 45.5], [39, 45.5, 39, 40.25], [53, 40.25, 53, 45.5], [53, 45.5, 56, 50], [36, 50, 56, 50]];
  if (segments.some(([x1, y1, x2, y2]) => distanceToSegment(x, y, x1, y1, x2, y2) <= strokeRadius)) return true;
  let previousX = 39;
  let previousY = 40.25;
  for (let step = 1; step <= 32; step += 1) {
    const angle = Math.PI - (Math.PI * step) / 32;
    const currentX = 46 + 7 * Math.cos(angle);
    const currentY = 40.25 - 7 * Math.sin(angle);
    if (distanceToSegment(x, y, previousX, previousY, currentX, currentY) <= strokeRadius) return true;
    previousX = currentX;
    previousY = currentY;
  }
  return Math.abs(Math.hypot(x - 46, y - 52) - 3) <= strokeRadius && y >= 52;
}

/** Samples one superscaled point using premultiplied colours for clean transparent edges. */
function samplePoint(x, y) {
  if (!insideRoundedSquare(x, y)) return [0, 0, 0, 0];
  if (insideBellStroke(x, y)) return foreground;
  if (insideBellFill(x, y)) return accent;
  if (insideDatabaseStroke(x, y)) return foreground;
  return background;
}

/** Renders one square BGRA bitmap with four-times supersampling for small Windows icon sizes. */
function renderBitmap(size) {
  const supersampling = 4;
  const pixels = Buffer.alloc(size * size * 4);
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const totals = [0, 0, 0, 0];
      for (let sampleY = 0; sampleY < supersampling; sampleY += 1) {
        for (let sampleX = 0; sampleX < supersampling; sampleX += 1) {
          const point = samplePoint(
            ((x + (sampleX + 0.5) / supersampling) / size) * 64,
            ((y + (sampleY + 0.5) / supersampling) / size) * 64,
          );
          for (let channel = 0; channel < 4; channel += 1) totals[channel] += point[channel];
        }
      }
      const samples = supersampling ** 2;
      const offset = (y * size + x) * 4;
      pixels[offset] = Math.round(totals[2] / samples);
      pixels[offset + 1] = Math.round(totals[1] / samples);
      pixels[offset + 2] = Math.round(totals[0] / samples);
      pixels[offset + 3] = Math.round(totals[3] / samples);
    }
  }
  return pixels;
}

/** Wraps a rendered BGRA bitmap in the Windows device-independent bitmap structure used by ICO files. */
function buildDib(size) {
  const pixels = renderBitmap(size);
  const maskStride = Math.ceil(size / 32) * 4;
  const mask = Buffer.alloc(maskStride * size);
  const header = Buffer.alloc(40);
  header.writeUInt32LE(40, 0);
  header.writeInt32LE(size, 4);
  header.writeInt32LE(size * 2, 8);
  header.writeUInt16LE(1, 12);
  header.writeUInt16LE(32, 14);
  header.writeUInt32LE(pixels.length, 20);
  const bottomUpPixels = Buffer.alloc(pixels.length);
  const rowBytes = size * 4;
  for (let row = 0; row < size; row += 1) {
    pixels.copy(bottomUpPixels, row * rowBytes, (size - row - 1) * rowBytes, (size - row) * rowBytes);
  }
  return Buffer.concat([header, bottomUpPixels, mask]);
}

/** Builds a multi-resolution Windows icon for the executable, window, Tray and installer. */
function buildIco() {
  const sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256];
  const images = sizes.map(buildDib);
  const header = Buffer.alloc(6 + sizes.length * 16);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  sizes.forEach((size, index) => {
    const entry = 6 + index * 16;
    header.writeUInt8(size === 256 ? 0 : size, entry);
    header.writeUInt8(size === 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(images[index].length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += images[index].length;
  });
  return Buffer.concat([header, ...images]);
}

/** Writes generated bytes or fails closed when verify mode detects drift. */
function processOutput(path, bytes, verify) {
  if (verify) {
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) throw new Error(`Generated brand asset is missing or stale: ${path}`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, bytes);
}

const verify = process.argv.includes("--verify");
const svg = Buffer.from(buildSvg(), "utf8");
processOutput(outputs.designSystemSvg, svg, verify);
processOutput(outputs.dashboardSvg, svg, verify);
processOutput(outputs.windowsIcon, buildIco(), verify);
console.log(verify ? "DB-Notifier brand assets verified." : "DB-Notifier brand assets generated.");
