/** Calculates the shortest distance from a point to a finite line segment. */
function distanceToSegment(x, y, x1, y1, x2, y2) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const denominator = dx * dx + dy * dy;
  const projection = denominator === 0 ? 0 : Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / denominator));
  return Math.hypot(x - (x1 + projection * dx), y - (y1 + projection * dy));
}

/**
 * Determines whether a point overlaps the database-cylinder outline at a requested raster weight.
 * @param {number} x Horizontal coordinate in the canonical 64-unit canvas.
 * @param {number} y Vertical coordinate in the canonical 64-unit canvas.
 * @param {number} strokeRadius Half of the requested logical stroke width.
 * @param {boolean} includeMiddleSeam Whether the internal middle seam is retained at this resolution.
 * @returns {boolean} True when the point belongs to the requested outline.
 */
function insideDatabaseStroke(x, y, strokeRadius, includeMiddleSeam) {
  let previousX = 45;
  let previousY = 10;
  for (let step = 1; step <= 64; step += 1) {
    const angle = (Math.PI * 2 * step) / 64;
    const currentX = 25 + 20 * Math.cos(angle);
    const currentY = 10 + 6.5 * Math.sin(angle);
    if (distanceToSegment(x, y, previousX, previousY, currentX, currentY) <= strokeRadius) return true;
    previousX = currentX;
    previousY = currentY;
  }
  if (distanceToSegment(x, y, 5, 10, 5, 41) <= strokeRadius ||
      distanceToSegment(x, y, 45, 10, 45, 41) <= strokeRadius) return true;
  for (const centreY of includeMiddleSeam ? [25, 40] : [40]) {
    previousX = 5;
    let previousY = centreY;
    for (let step = 1; step <= 32; step += 1) {
      const angle = Math.PI - (Math.PI * step) / 32;
      const currentX = 25 + 20 * Math.cos(angle);
      const currentY = centreY + 6.5 * Math.sin(angle);
      if (distanceToSegment(x, y, previousX, previousY, currentX, currentY) <= strokeRadius) return true;
      previousX = currentX;
      previousY = currentY;
    }
  }
  return false;
}

/** Returns whether a point lies within the lower-right notification bell accent. */
function insideBellFill(x, y) {
  if (y >= 49.5 && y <= 55) {
    const expansion = ((y - 49.5) * 4) / 5.5;
    return x >= 38 - expansion && x <= 56 + expansion;
  }
  if (y >= 41 && y <= 49.5 && x >= 38 && x <= 56) return true;
  const bodyHalfWidth = 9 * Math.sqrt(Math.max(0, 1 - ((y - 41) / 9) ** 2));
  return y >= 32 && y <= 41 && Math.abs(x - 47) <= bodyHalfWidth;
}

/**
 * Determines whether a point overlaps the bell outline or clapper at the requested raster weight.
 * @param {number} x Horizontal coordinate in the canonical 64-unit canvas.
 * @param {number} y Vertical coordinate in the canonical 64-unit canvas.
 * @param {number} strokeRadius Half of the requested logical stroke width.
 * @returns {boolean} True when the point belongs to the requested bell stroke.
 */
function insideBellStroke(x, y, strokeRadius) {
  const segments = [[34, 55, 38, 49.5], [38, 49.5, 38, 41], [56, 41, 56, 49.5], [56, 49.5, 60, 55], [34, 55, 60, 55]];
  if (segments.some(([x1, y1, x2, y2]) => distanceToSegment(x, y, x1, y1, x2, y2) <= strokeRadius)) return true;
  let previousX = 38;
  let previousY = 41;
  for (let step = 1; step <= 32; step += 1) {
    const angle = Math.PI - (Math.PI * step) / 32;
    const currentX = 47 + 9 * Math.cos(angle);
    const currentY = 41 - 9 * Math.sin(angle);
    if (distanceToSegment(x, y, previousX, previousY, currentX, currentY) <= strokeRadius) return true;
    previousX = currentX;
    previousY = currentY;
  }
  return Math.abs(Math.hypot(x - 47, y - 57) - 4) <= strokeRadius && y >= 57;
}

/**
 * Classifies one supersampled point using resolution-aware strokes for small Windows surfaces.
 * @param {number} x Horizontal coordinate in the canonical 64-unit canvas.
 * @param {number} y Vertical coordinate in the canonical 64-unit canvas.
 * @param {number} size Output bitmap edge length in pixels.
 * @returns {number} Index of the foremost semantic drawing layer at this point.
 */
function sampleLayer(x, y, size) {
  const databaseStrokeRadius = Math.max(1.5, 48 / size);
  const bellStrokeRadius = size <= 24 ? 28 / size : 1.25;
  const keylineDelta = size <= 24 ? 24 / size : 1.25;
  const includeMiddleSeam = true;
  if (insideBellStroke(x, y, bellStrokeRadius)) return 0;
  if (insideBellFill(x, y)) return 1;
  if (insideBellStroke(x, y, bellStrokeRadius + keylineDelta)) return 2;
  if (insideDatabaseStroke(x, y, databaseStrokeRadius, includeMiddleSeam)) return 3;
  if (insideDatabaseStroke(x, y, databaseStrokeRadius + keylineDelta, includeMiddleSeam)) return 4;
  return 5;
}

/**
 * Precomputes supersampled layer coverage once for every semantic status variant.
 * @param {number} size Output bitmap edge length in pixels.
 * @returns {Buffer} Six-layer coverage counts for every output pixel.
 */
function renderCoverage(size) {
  const supersampling = size <= 20 ? 1 : size <= 24 ? 2 : 4;
  const sampleWeight = 16 / (supersampling ** 2);
  const coverage = Buffer.alloc(size * size * 6);
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      for (let sampleY = 0; sampleY < supersampling; sampleY += 1) {
        for (let sampleX = 0; sampleX < supersampling; sampleX += 1) {
          const layer = sampleLayer(
            ((x + (sampleX + 0.5) / supersampling) / size) * 64,
            ((y + (sampleY + 0.5) / supersampling) / size) * 64,
            size,
          );
          coverage[(y * size + x) * 6 + layer] += sampleWeight;
        }
      }
    }
  }
  return coverage;
}

/**
 * Renders one square premultiplied BGRA bitmap from shared layer coverage.
 * @param {number} size Output bitmap edge length in pixels.
 * @param {number[]} accent Semantic bell colour as RGBA channels.
 * @param {Buffer} coverage Precomputed six-layer supersampling coverage.
 * @returns {Buffer} Premultiplied BGRA bitmap bytes for the ICO payload.
 */
function renderBitmap(size, accent, coverage) {
  const samples = 16;
  const pixels = Buffer.alloc(size * size * 4);
  const rasterDatabaseStroke = size <= 32 ? smallDatabaseStroke : databaseStroke;
  const rasterBellStroke = size <= 32 ? accent : bellStroke;
  const colours = [rasterBellStroke, accent, adaptiveKeyline, rasterDatabaseStroke, adaptiveKeyline, transparent];
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      const totals = [0, 0, 0, 0];
      const coverageOffset = (y * size + x) * 6;
      for (let layer = 0; layer < colours.length; layer += 1) {
        const count = coverage[coverageOffset + layer];
        for (let channel = 0; channel < 4; channel += 1) totals[channel] += colours[layer][channel] * count;
      }
      const offset = (y * size + x) * 4;
      pixels[offset] = Math.round(totals[2] / samples);
      pixels[offset + 1] = Math.round(totals[1] / samples);
      pixels[offset + 2] = Math.round(totals[0] / samples);
      pixels[offset + 3] = Math.round(totals[3] / samples);
    }
  }
  return pixels;
}

/** Wraps a rendered BGRA bitmap in the Windows device-independent bitmap structure used by ICO files. */
function buildDib(size, accent, coverage) {
  const pixels = renderBitmap(size, accent, coverage);
  const maskStride = Math.ceil(size / 32) * 4;
  const mask = Buffer.alloc(maskStride * size);
  const header = Buffer.alloc(40);
  header.writeUInt32LE(40, 0);
  header.writeInt32LE(size, 4);
  header.writeInt32LE(size * 2, 8);
  header.writeUInt16LE(1, 12);
  header.writeUInt16LE(32, 14);
  header.writeUInt32LE(pixels.length, 20);
  const bottomUpPixels = Buffer.alloc(pixels.length);
  const rowBytes = size * 4;
  for (let row = 0; row < size; row += 1) {
    pixels.copy(bottomUpPixels, row * rowBytes, (size - row - 1) * rowBytes, (size - row) * rowBytes);
  }
  return Buffer.concat([header, bottomUpPixels, mask]);
}

/**
 * Builds a multi-resolution icon for Windows shell surfaces or the browser favicon.
 * @param {number[]} accent Semantic bell colour as RGBA channels.
 * @param {Map<number, Buffer>} coverageBySize Shared resolution-specific layer coverage.
 * @param {number[]} sizes Ordered icon resolutions to include in the ICO directory.
 * @returns {Buffer} Complete multi-resolution ICO bytes.
 */
function buildIco(accent, coverageBySize, sizes = iconSizes) {
  const images = sizes.map((size) => buildDib(size, accent, coverageBySize.get(size)));
  const header = Buffer.alloc(6 + sizes.length * 16);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  sizes.forEach((size, index) => {
    const entry = 6 + index * 16;
    header.writeUInt8(size === 256 ? 0 : size, entry);
    header.writeUInt8(size === 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(images[index].length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += images[index].length;
  });
  return Buffer.concat([header, ...images]);
}

/** Writes generated bytes or fails closed when verify mode detects drift. */
function processOutput(path, bytes, verify) {
  if (verify) {
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) throw new Error(`Generated brand asset is missing or stale: ${path}`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, bytes);
}

